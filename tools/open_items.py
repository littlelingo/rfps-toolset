"""Make the assertions and open items in response/*.md easy to find and work through.

Markers keep their square-bracket form ([ASSERTION: ...], [DECISION: ...], [OPEN: ...], [EVIDENCE NEEDED: ...])
because the build and the reports read that form. This tool adds two scan aids:
  1. an optional colored icon before each marker (Markdown cannot color text, so the icon carries the color):
       🔴 DECISION   🟠 OPEN   🟣 EVIDENCE NEEDED   🟡 ASSERTION
     The build ignores the icon (and removes it with the marker in FINAL). Add or refresh the icons with --mark.
  2. open-items.md in the solution folder: every marker in one table, worked from the top down, with a link to
     the line, the section, and what it says. It is regenerated; do not edit it by hand.

Usage: rfps-open-items [--solution [folder]] [--mark]
"""
import argparse, pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import build_response as br

KINDS = [("DECISION", "\U0001F534", "Decide, then replace the marker with the final text"),
         ("OPEN", "\U0001F7E0", "Unanswered question or missing fact; resolve or state the assumption"),
         ("EVIDENCE NEEDED", "\U0001F7E3", "Claim needs a register row or a source"),
         ("ASSERTION", "\U0001F7E1", "Claim without a register row; support it or accept it knowingly")]
ICON = {k: i for k, i, _ in KINDS}
NAMES = "|".join(k for k, _, _ in KINDS)
MARK = re.compile(r"(?:[\U0001F7E1\U0001F534\U0001F7E0\U0001F7E3]️?[ \t]*)?(\[(%s)[^\]]*\])" % NAMES, re.S)

def mark_files(rdir):
    n = 0
    for f in sorted(rdir.glob("*.md")):
        t = f.read_text()
        new = MARK.sub(lambda m: ICON[m.group(2)] + " " + m.group(1), t)
        if new != t:
            f.write_text(new); n += 1
    return n

def scan(rdir):
    items = []
    for f in sorted(rdir.glob("*.md")):
        t = f.read_text(); heading = f.stem
        starts = [0]
        for m in re.finditer("\n", t): starts.append(m.end())
        def line_of(pos):
            import bisect
            return bisect.bisect_right(starts, pos)
        heads = [(m.start(), m.group(2).strip()) for m in re.finditer(r"^(#{1,6})\s+(.+)$", t, re.M)]
        for m in MARK.finditer(t):
            h = [x for x in heads if x[0] <= m.start()]
            items.append(dict(kind=m.group(2), file=f.name, line=line_of(m.start()), section=(h[-1][1] if h else f.stem),
                              text=re.sub(r"\s+", " ", re.sub(r"^\[[A-Z ]+:?\s*", "", m.group(1)).rstrip("]")).strip()))
    order = {k: i for i, (k, _, _) in enumerate(KINDS)}
    return sorted(items, key=lambda x: (order[x["kind"]], x["file"], x["line"]))

def write(sol, cfg=None):
    sol = pathlib.Path(sol)
    rdir = sol / ((cfg or {}).get("response_dir", "response"))
    items = scan(rdir)
    cnt = {k: sum(1 for x in items if x["kind"] == k) for k, _, _ in KINDS}
    out = ["# Open items in the response", "",
           "Generated by `rfps-open-items` (and by `/rfps:refresh-reports`). Do not edit; fix the marker in `response/*.md` and re-run. Work from the top: decisions first, then open questions, evidence gaps, and finally assertions.", "",
           "| Icon | Marker | Count | What to do |", "|------|--------|-------|-----------|"]
    for k, i, d in KINDS: out.append(f"| {i} | {k} | {cnt[k]} | {d} |")
    out += ["", f"**Total:** {len(items)} markers", ""]
    for k, i, d in KINDS:
        rows = [x for x in items if x["kind"] == k]
        if not rows: continue
        out += [f"## {i} {k} ({len(rows)})", "", "| # | Where | Section | What it says |", "|---|-------|---------|--------------|"]
        for n, x in enumerate(rows, 1):
            link = f"[{x['file']}:{x['line']}](response/{x['file']}:{x['line']})"
            txt = x["text"].replace("|", "/")
            txt = txt if len(txt) <= 220 else txt[:217] + "..."
            out.append(f"| {n} | {link} | {x['section'].replace('|', '/')} | {txt} |")
        out.append("")
    (sol / "open-items.md").write_text("\n".join(out))
    return len(items), cnt

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--solution", nargs="?", const="", default="")
    ap.add_argument("--mark", action="store_true", help="add or refresh the colored icon before every marker in response/*.md")
    a = ap.parse_args()
    import tomllib
    sol = br.resolve_solution(a.solution or None)
    cfg = tomllib.loads((sol / "solution.toml").read_text())
    if a.mark:
        print(f"icons added or refreshed in {mark_files(sol / cfg.get('response_dir', 'response'))} file(s)")
    n, cnt = write(sol, cfg)
    print(f"open-items.md: {n} markers (" + ", ".join(f"{cnt[k]} {k}" for k, _, _ in KINDS) + ")")

if __name__ == "__main__":
    main()
