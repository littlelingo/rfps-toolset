"""The evaluator's map: for every requirement in coverage-matrix.md, where in the response it is answered.

An evaluator scoring a stack of proposals finds a requirement fastest when the response says where it is answered. This writes
cross-reference.md (regenerated each time; do not edit) with one row per requirement: its solicitation reference, whether it is mandatory,
and the response sections that answer it with an estimated page. A section answers a requirement when it cites the clause ("RFP 2.1", "(RFP 2.1, 2.3)")
or when one of its sentences shares most of the requirement's wording. A mandatory requirement no section answers is listed first.
The page is an estimate at 500 words a page from the start of the response, so treat it as a pointer, not a page number to print.

Usage: rfps-crossref [--solution [folder]]
"""
import argparse, collections, pathlib, re, sys, tomllib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import build_response as br
import strategy as sg
import solicit_text as st
import lint

PROCEDURAL = re.compile(r"\b(?:due|deadline|no later than|not exceed \d+ pages?|font|margins?|(?:e-?mailed?|delivered|submitted) (?:by|via|to)|signed|signature)\b", re.I)

def clauses(source):
    return set(re.findall(r"\d+(?:\.\d+)*", source or ""))

def cited_clauses(text):
    """Clause numbers a section cites, such as 'RFP 2.1', '(RFP 2.1, 2.3)' or 'Section 3'."""
    out = set()
    for m in re.finditer(r"(?:RFP|Section|Sections|§|Amendment \d+)\s*((?:\d+(?:\.\d+)*(?:\s*(?:,|;|and|&|-|to)\s*)?)+)", text, re.I):
        out |= set(re.findall(r"\d+(?:\.\d+)*", m.group(1)))
    return out

def build(sol, cfg):
    f = sol / "coverage-matrix.md"
    reqs = sg.rows(f.read_text(), r"R-\d{3}", 9) if f.is_file() else {}
    groups = lint.groups_of(sol, cfg); start, acc = {}, 0
    for h, t in groups.items():
        start[h] = 1 + int(acc / 500); acc += len(re.findall(r"\S+", lint.clean(t)))
    cites = {h: cited_clauses(lint.clean(t)) for h, t in groups.items()}
    sents = {h: [s for l in lint.body_lines(t) for s in re.split(r"(?<=[.;!?])\s+", l) if len(s.split()) >= 5] for h, t in groups.items()}
    rows = []
    for rid, c in reqs.items():
        text, source, mand = c[1], c[2], c[3].lower().startswith(("y", "m"))
        found = collections.OrderedDict()
        cl = clauses(source)
        for h in groups:
            if cl and cl & cites[h]: found[h] = "cites " + ", ".join(sorted(cl & cites[h]))
        if not found:
            for h in groups:
                rt = st._tokens(text)
                best = max((len(rt & st._tokens(s)) / len(rt) for s in sents[h]), default=0) if rt else 0
                if best >= 0.5: found[h] = f"wording ({best:.0%} shared)"
        note = "an amendment change: applied through the requirement it changes" if source.lower().startswith("amendment") else ("a submission step: tracked in submission.md" if PROCEDURAL.search(text) else "")
        rows.append(dict(id=rid, text=text, source=source, mandatory=mand and not note, found=found, note=note, implicit="(implicit)" in text.lower()))
    return rows, start

def checks(sol, cfg):
    rows, _ = build(sol, cfg)
    if not rows: return ["| Every mandatory requirement is answered in a named section | Info | no requirement rows in coverage-matrix.md |"]
    miss = [r["id"] for r in rows if r["mandatory"] and not r["found"]]
    return [f"| Every mandatory requirement is answered in a named section | {'Pass' if not miss else 'Open'} | {sum(1 for r in rows if r['mandatory'])} mandatory; " + (f"no section found for: {', '.join(miss[:10])}" if miss else "each has a section (see cross-reference.md)") + " |"]

def write(sol, cfg):
    rows, start = build(sol, cfg)
    out = ["# Requirement Cross-Reference", "", "Generated by `rfps-crossref` (and by `/rfps:refresh-reports`). Do not edit; fix the response or the coverage matrix and re-run. Pages are estimated at 500 words a page from the start of the response.", ""]
    miss = [r for r in rows if r["mandatory"] and not r["found"]]
    out += [f"**Requirements:** {len(rows)} ({sum(1 for r in rows if r['mandatory'])} mandatory). **Mandatory with no answering section found:** {len(miss)}", ""]
    out += ["| # | Requirement | Reference | Mandatory | Answered in (estimated page) | How found |", "|---|-------------|-----------|-----------|------------------------------|-----------|"]
    for r in sorted(rows, key=lambda r: (bool(r["found"]) or bool(r["note"]), r["id"])):
        where = "; ".join(f"{h} (p. {start[h]})" for h in r["found"]) or (f"n/a: {r['note']}" if r["note"] else "**not found**")
        how = "; ".join(sorted(set(v.split(" ")[0] for v in r["found"].values()))) or "-"
        out.append(f"| {r['id']} | {r['text'].replace('|', '/')[:140]} | {r['source']} | {'Yes' if r['mandatory'] else 'No'} | {where} | {how} |")
    (sol / "cross-reference.md").write_text("\n".join(out) + "\n")
    return len(rows), len(miss)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--solution", nargs="?", const="", default="")
    a = ap.parse_args()
    sol = br.resolve_solution(a.solution or None); cfg = tomllib.loads((sol / "solution.toml").read_text())
    n, m = write(sol, cfg)
    print(f"cross-reference.md: {n} requirement(s), {m} mandatory with no answering section found")

if __name__ == "__main__":
    main()
